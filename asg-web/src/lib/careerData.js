export function getScoreInterpretation(score) {
  if (score >= 13) {
    return { level: 'Strong Preference', color: '#10B981', desc: 'Your strongest natural inclination. You will excel in roles centered here.' };
  } else if (score >= 10) {
    return { level: 'Moderate Preference', color: '#3B82F6', desc: 'A solid, healthy interest. Highly viable as a primary or complementary domain.' };
  } else if (score >= 7) {
    return { level: 'Worth Exploring', color: '#F59E0B', desc: 'Emerging or situational interest. Worth exploring through projects.' };
  } else {
    return { level: 'Low Inclination', color: '#6B7280', desc: 'Less preferred based on your current instinctive responses.' };
  }
}

export function computeAssessmentResults(answers) {
  const scores = {};
  CAREER_CATEGORIES.forEach(cat => {
    scores[cat.code] = 0;
  });

  CAREER_QUESTIONS.forEach(q => {
    const val = Number(answers[q.q]) || 0;
    scores[q.c] = (scores[q.c] || 0) + val;
  });

  const rankedCategories = CAREER_CATEGORIES.map(cat => ({
    code: cat.code,
    name: cat.name,
    tagline: cat.tagline,
    icon: cat.icon,
    color: cat.color,
    score: scores[cat.code] || 0,
    roles: cat.roles,
    skillsToBuild: cat.skillsToBuild,
    actionPlan: cat.actionPlan,
    interpretation: getScoreInterpretation(scores[cat.code] || 0)
  })).sort((a, b) => b.score - a.score);

  const top3 = rankedCategories.slice(0, 3).map((item, idx) => ({
    ...item,
    badge: idx === 0 ? 'Primary Swadharma' : idx === 1 ? 'Secondary Complement' : 'Tertiary Explorer'
  }));

  // Complimentary synergy synthesis
  const synergyKey = `${top3[0].code}+${top3[1].code}`;
  const synergyMap = {
    'S+X': 'Technical Sales & Solution Consulting — Bridging complex tech and client relationships.',
    'X+S': 'Technical Sales & Solution Consulting — High technical competence with persuasion.',
    'C+X': 'UI/UX Design, Creative Tech & Product Engineering — Designing intuitive digital experiences.',
    'X+C': 'Creative Technology & Product Prototyping — Engineering with sharp aesthetic vision.',
    'E+L': 'Startup Founder & Venture Executive — High-ownership leadership and scaling ventures.',
    'L+E': 'Venture Leadership & Strategic General Management — Steering organizations with entrepreneurial grit.',
    'F+R': 'Quantitative Research & Investment Strategy — Deep empirical data analysis with fiscal intelligence.',
    'R+F': 'Financial Data Science & Market Research — Evidence-backed financial problem solving.',
    'T+P': 'Corporate Training & Talent Development — Nurturing human potential through impactful education.',
    'P+T': 'People Development & Culture Coaching — Empathetic mentoring and organizational learning.',
    'O+L': 'Operations Director & Program Management — Flawless project execution backed by leadership.',
    'L+O': 'Operational Leadership — Driving disciplined execution across cross-functional teams.'
  };

  const synergyInsight = synergyMap[synergyKey] || 
    `A powerful hybrid profile combining ${top3[0].name} with ${top3[1].name}. Careers that bridge these two disciplines will offer you the greatest fulfillment.`;

  return {
    scores,
    rankedCategories,
    top3,
    synergyInsight
  };
}
